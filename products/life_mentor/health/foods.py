"""Bundled food composition table (LM06): a USDA FoodData Central SR Legacy subset.

The bundle ``data/usda_sr_legacy_subset.json`` was generated by
``life_mentor.health.usda.build_subset`` from the official CSV release (the
download URL, release and zip sha256 are in its ``dataset`` block). Amounts are
per 100 g edible portion and are loaded as Decimal from their original strings.
No GI, IFCT or INDB data are ever bundled (SPEC-GAP LM-G2).
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass, field
from decimal import Decimal
from pathlib import Path
from typing import Any

__all__ = ["BUNDLE_PATH", "Food", "FoodTable", "load_food_table"]

BUNDLE_PATH = Path(__file__).resolve().parent / "data" / "usda_sr_legacy_subset.json"


@dataclass(frozen=True)
class Food:
    key: str
    fdc_id: str
    description: str
    data_type: str
    nutrients: dict[str, Decimal]
    portions: tuple[dict[str, Any], ...] = ()


@dataclass(frozen=True)
class FoodTable:
    dataset: dict[str, Any]
    nutrients: dict[str, dict[str, str]]
    foods: dict[str, Food] = field(default_factory=dict)

    @property
    def empty(self) -> bool:
        return not self.foods

    def get(self, key: str) -> Food:
        return self.foods[key]

    def nutrient_meta(self, nid: str) -> dict[str, str]:
        return self.nutrients.get(nid, {"name": nid, "unit": "?"})


def _decimal(raw: Any, where: str) -> Decimal:
    if not isinstance(raw, str):
        raise TypeError(f"{where}: amounts must be stored as strings, got {type(raw).__name__}")
    value = Decimal(raw)
    if not value.is_finite() or value < 0:
        raise ValueError(f"{where}: invalid amount {raw!r}")
    return value


def load_food_table(path: str | os.PathLike[str] = BUNDLE_PATH) -> FoodTable:
    """Load a bundle written by ``usda.write_bundle`` (amounts become Decimal)."""
    raw = json.loads(Path(path).read_text(encoding="utf-8"))
    foods: dict[str, Food] = {}
    for key, f in raw.get("foods", {}).items():
        foods[key] = Food(
            key=key,
            fdc_id=str(f["fdc_id"]),
            description=str(f["description"]),
            data_type=str(f.get("data_type", "")),
            nutrients={nid: _decimal(v, f"{key}.{nid}") for nid, v in f["nutrients"].items()},
            portions=tuple(f.get("portions", [])),
        )
    return FoodTable(dataset=dict(raw.get("dataset", {})),
                     nutrients=dict(raw.get("nutrients", {})), foods=foods)
